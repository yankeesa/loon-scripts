/**
 * 凯尔资 · 设为【副设备】（在副设备上手动运行一次即可，重复运行无副作用）
 *
 * 背景：iPad / iPhone 共用同一套 Loon 配置且强制同步，两台会在同一时刻
 *       各自跑一遍签到。点赞接口是 toggle（同一帖点两次 = 取消赞），
 *       两台对同一批新帖各点一次 → 互相抵消 → 当日点赞积分 0。
 *       评论是新增内容、无 toggle 语义，所以一直正常。
 *
 * 关键：Loon 的 $persistentStore 是【每台设备本地】的，不随配置同步
 *       （你观察到「两台各记各的进度」正是证据）。把角色存在这里，
 *       两台设备的插件/配置可以完全一模一样，但只有主设备真正跑定时。
 *
 * 本脚本只做一件事：把【本设备】标记为 idle。幂等，点几次都是副设备，
 * 不会像「切换」那样误把主设备翻成副设备。
 * 需要改回主设备时，在 Loon 里运行「凯尔资_设为主设备_手动运行」。
 *
 * 挂在一条「2 月 30 日」的 cron 上（永不自动触发），仅用于让脚本出现在
 * Loon 脚本列表里供手动运行，不会产生任何定时任务。
 */
const KEY = "kaierzi_role_v9";
$persistentStore.write("idle", KEY);
$notification.post(
  "凯尔资 · 设备角色",
  "✅ 本设备已设为【副设备】",
  "定时任务将静默跳过，不再参与点赞。\n请确认另一台设备保持【主设备】（不点，或点「凯尔资_设为主设备_手动运行」）。"
);
$done();
