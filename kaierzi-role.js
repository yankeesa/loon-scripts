/**
 * 凯尔资 · 设备角色切换（只需在【副设备】手动运行一次）
 *
 * 背景：iPad / iPhone 共用同一套 Loon 配置且强制同步，两台会在同一时刻
 *       各自跑一遍签到。点赞接口是 toggle（同一帖点两次 = 取消赞），
 *       两台对同一批新帖各点一次 → 互相抵消 → 当日点赞积分 0。
 *       评论是新增内容、无 toggle 语义，所以一直正常。
 *
 * 关键：Loon 的 $persistentStore 是【每台设备本地】的，不随配置同步
 *       （你观察到「两台各记各的进度」正是证据）。把角色存在这里，
 *       两台设备的插件/配置可以完全一模一样，但只有主设备真正跑定时。
 *
 * 用法：
 *   - 在【副设备】上手动运行本脚本一次 → 该设备标记 idle，定时静默跳过；
 *   - 【主设备】不用动（无标记 = 正常跑）；
 *   - 再运行一次可切回主设备（需要换主力机时用）。
 *
 * 本脚本挂在一条「2 月 30 日」的 cron 上（永不自动触发），仅用于让脚本
 * 出现在 Loon 脚本列表里供手动运行，不会产生任何定时任务。
 */
const KEY = "kaierzi_role_v9";
const cur = $persistentStore.read(KEY);
const next = cur === "idle" ? "primary" : "idle";
$persistentStore.write(next, KEY);

if (next === "idle") {
  $notification.post(
    "凯尔资 · 设备角色",
    "✅ 本设备已设为【副设备】",
    "定时任务将静默跳过，不再参与点赞。\n另一台设备不用动，请确认它保持默认（主设备）。"
  );
} else {
  $notification.post(
    "凯尔资 · 设备角色",
    "✅ 本设备已设为【主设备】",
    "定时任务正常运行。\n注意：两台设备不能同时是主设备，否则点赞仍会互相抵消。"
  );
}
$done();
